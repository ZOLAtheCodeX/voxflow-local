import AppKit
import Foundation
import os

/// Every item on a pasteboard, each as its representations in the order the
/// owner offered them. An empty `items` array is the empty clipboard.
struct PasteboardSnapshot: Equatable, Sendable {
    struct Representation: Equatable, Sendable {
        let type: String
        let data: Data
    }

    struct Item: Equatable, Sendable {
        let representations: [Representation]
    }

    let items: [Item]

    static let empty = PasteboardSnapshot(items: [])

    /// Total payload size across every representation, used to bound what a
    /// caller is willing to hold in memory.
    var byteCount: Int {
        items.reduce(0) { total, item in
            total + item.representations.reduce(0) { $0 + $1.data.count }
        }
    }
}

/// The pasteboard boundary the temporary-paste logic is written against, so
/// tests can drive it with an in-memory fake. The real implementation is
/// `SystemPasteboard`.
@MainActor
protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }

    /// Reads every item and every type that currently has data.
    func snapshot() -> PasteboardSnapshot

    /// Replaces the contents with `text` as this host's transient,
    /// auto-generated content. Returns the change count after the write, or
    /// nil when the write failed.
    func writeTemporary(_ text: String) -> Int?

    /// Replaces the contents with exactly `snapshot`'s items and types.
    func restore(_ snapshot: PasteboardSnapshot)
}

/// `PasteboardAccess` over one `NSPasteboard` (the general pasteboard by
/// default).
///
/// Ownership rule: only `TemporaryPasteboard` may call `writeTemporary` and
/// `restore`. Everything else that writes the general pasteboard for the user
/// goes through `SystemClipboard.copy`. Keeping one owner means a restore can
/// never clobber a copy the user made after the temporary write.
@MainActor
final class SystemPasteboard: PasteboardAccess {
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private static let log = Logger(subsystem: "local.voxflow.app", category: "SystemPasteboard")

    private let pasteboard: NSPasteboard

    init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var changeCount: Int { pasteboard.changeCount }

    func snapshot() -> PasteboardSnapshot {
        var items: [PasteboardSnapshot.Item] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var representations: [PasteboardSnapshot.Representation] = []
            for type in item.types {
                // A type whose owner never supplies data reads back as nil;
                // skip it rather than restoring an empty stand-in.
                guard let data = item.data(forType: type) else { continue }
                representations.append(.init(type: type.rawValue, data: data))
            }
            if !representations.isEmpty {
                items.append(.init(representations: representations))
            }
        }
        return PasteboardSnapshot(items: items)
    }

    func writeTemporary(_ text: String) -> Int? {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // The nspasteboard.org markers are presence-only; the payload is empty.
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        guard pasteboard.writeObjects([item]) else {
            Self.log.error("Temporary pasteboard write failed")
            return nil
        }
        // changeCount advances on prepareForNewContents, not on writeObjects,
        // so it is read after the write succeeds.
        return pasteboard.changeCount
    }

    /// Restores the user's content verbatim. No markers are added: the
    /// restored content is exactly what the user had, so clipboard managers
    /// treat it as the ordinary copy it was.
    func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else { return }
        let items = snapshot.items.map { source -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for representation in source.representations {
                item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
            }
            return item
        }
        if !pasteboard.writeObjects(items) {
            Self.log.error("Pasteboard restore failed (\(snapshot.items.count) items)")
        }
    }
}

/// The production writer for deliberate copies (the user pressed Copy, or a
/// recovery path hands text back). A plain `.string` write to the general
/// pasteboard, with none of the temporary-paste markers, so clipboard
/// managers record it like any other copy.
enum SystemClipboard {
    @MainActor
    static func copy(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }
}
