import AppKit
import XCTest
@testable import VoxFlowApp

/// Exercises `SystemPasteboard` against a uniquely named pasteboard (never
/// `NSPasteboard.general`), because only a real pasteboard proves that every
/// representation survives a snapshot and restore round trip.
@MainActor
final class SystemPasteboardTests: XCTestCase {

    private let transientType = "org.nspasteboard.TransientType"
    private let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    private let concealedType = "org.nspasteboard.ConcealedType"

    /// Supplies no data for any requested type, like a lazy owner that has
    /// gone away.
    private final class SilentProvider: NSObject, NSPasteboardItemDataProvider {
        func pasteboard(
            _ pasteboard: NSPasteboard?,
            item: NSPasteboardItem,
            provideDataForType type: NSPasteboard.PasteboardType
        ) {}
    }

    private func makeSUT() throws -> (NSPasteboard, SystemPasteboard) {
        let pasteboard = NSPasteboard.withUniqueName()
        addTeardownBlock { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        pasteboard.setString("probe", forType: .string)
        guard pasteboard.string(forType: .string) == "probe" else {
            throw XCTSkip("No pasteboard server on this runner; representation round trips not exercised")
        }
        pasteboard.clearContents()
        return (pasteboard, SystemPasteboard(pasteboard))
    }

    func test_snapshot_and_restore_round_trip_preserves_every_item_and_type() throws {
        let (pb, sut) = try makeSUT()
        let rich = NSPasteboardItem()
        rich.setString("hello", forType: .string)
        rich.setData(Data("{\\rtf1 hi}".utf8), forType: .rtf)
        let image = NSPasteboardItem()
        image.setData(Data([0x89, 0x50, 0x4E, 0x47]), forType: .png)
        let file = NSPasteboardItem()
        file.setString(URL(fileURLWithPath: "/tmp/x.txt").absoluteString, forType: .fileURL)
        pb.clearContents()
        pb.writeObjects([rich, image, file])

        let snap = sut.snapshot()
        XCTAssertEqual(snap.items.count, 3)
        XCTAssertTrue(snap.items[0].representations.map(\.type).contains("public.rtf"))
        XCTAssertEqual(snap.items[1].representations.map(\.type), ["public.png"])

        pb.clearContents()
        pb.setString("other", forType: .string)
        sut.restore(snap)

        XCTAssertEqual(sut.snapshot(), snap)
    }

    func test_empty_clipboard_snapshots_empty_and_restores_empty() throws {
        let (pb, sut) = try makeSUT()
        pb.clearContents()
        XCTAssertEqual(sut.snapshot(), .empty)

        pb.setString("x", forType: .string)
        sut.restore(.empty)

        XCTAssertEqual(pb.pasteboardItems?.count ?? 0, 0)
    }

    func test_write_temporary_carries_text_and_both_markers() throws {
        let (pb, sut) = try makeSUT()
        let count = sut.writeTemporary("dictated")

        XCTAssertEqual(count, pb.changeCount)
        XCTAssertEqual(pb.string(forType: .string), "dictated")
        let types = (pb.types ?? []).map(\.rawValue)
        XCTAssertTrue(types.contains(transientType))
        XCTAssertTrue(types.contains(autoGeneratedType))
    }

    func test_write_temporary_preserves_multiline_and_emoji_text() throws {
        let (pb, sut) = try makeSUT()
        let text = "line one\nnaïve café 👩🏽‍💻\n\tindented"
        XCTAssertNotNil(sut.writeTemporary(text))
        XCTAssertEqual(pb.string(forType: .string), text)
    }

    func test_restore_keeps_concealed_marker() throws {
        let (pb, sut) = try makeSUT()
        let item = NSPasteboardItem()
        item.setString("s3cret", forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType(concealedType))
        pb.clearContents()
        pb.writeObjects([item])
        let snap = sut.snapshot()

        pb.clearContents()
        sut.restore(snap)

        XCTAssertTrue((pb.types ?? []).map(\.rawValue).contains(concealedType))
        XCTAssertEqual(pb.string(forType: .string), "s3cret")
    }

    func test_snapshot_skips_types_whose_provider_supplies_nothing() throws {
        let (pb, sut) = try makeSUT()
        let lazyType = NSPasteboard.PasteboardType("com.example.lazy")
        let provider = SilentProvider()
        let item = NSPasteboardItem()
        item.setString("visible", forType: .string)
        item.setDataProvider(provider, forTypes: [lazyType])
        pb.clearContents()
        pb.writeObjects([item])

        let snap = sut.snapshot()
        let types = snap.items.flatMap(\.representations).map(\.type)
        XCTAssertFalse(types.contains("com.example.lazy"))
        XCTAssertTrue(types.contains("public.utf8-plain-text"))

        pb.clearContents()
        sut.restore(snap)
        XCTAssertEqual(pb.string(forType: .string), "visible")
        withExtendedLifetime(provider) {}
    }

    func test_large_payload_round_trips() throws {
        let (pb, sut) = try makeSUT()
        let big = Data(repeating: 0xAB, count: 5_000_000)
        let item = NSPasteboardItem()
        item.setData(big, forType: .tiff)
        pb.clearContents()
        pb.writeObjects([item])

        let snap = sut.snapshot()
        pb.clearContents()
        sut.restore(snap)

        XCTAssertEqual(pb.data(forType: .tiff), big)
        XCTAssertGreaterThanOrEqual(snap.byteCount, 5_000_000)
    }
}
